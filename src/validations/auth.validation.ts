import Joi from "joi";

export const jwtVerifySchema = Joi.object({
    jwtFromAppwrite: Joi.string().required()
});

// Google ID tokens are always 3-segment base64url JWTs.
export const googleNativeLoginSchema = Joi.object({
    idToken: Joi.string()
        .required()
        .max(8192)
        .pattern(/^[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$/)
        .messages({
            "string.pattern.base": "idToken must be a valid ID token",
            "string.max": "idToken is too long",
        })
});


// The redirect target is embedded in a signed state token and later rendered in
// the callback page, so only well formed deep links / http(s) URLs are accepted
// and script-capable schemes are rejected.
const redirectUriSchema = Joi.string()
    .required()
    .max(2048)
    .pattern(/^[A-Za-z][A-Za-z0-9+.\-]*:\/\/[^"'<>\s]+$/)
    .custom((value, helpers) => {
        const scheme = value.slice(0, value.indexOf(":")).toLowerCase();
        if (scheme === "javascript" || scheme === "data" || scheme === "vbscript") {
            return helpers.error("any.invalid");
        }
        return value;
    })
    .messages({
        "string.pattern.base": "redirectUri must be a valid deep link or http(s) URL",
        "any.invalid": "redirectUri scheme is not allowed",
        "string.max": "redirectUri is too long",
    });

// flow nonce generated by the client instance
const nonceSchema = Joi.string()
    .required()
    .pattern(/^[a-f0-9]{64}$/)
    .messages({
        "string.pattern.base": "nonce must be a 64 character lowercase hex string",
    });

export const googleLoginSchema = Joi.object({
    redirectUri: redirectUriSchema,
    nonce: nonceSchema,
});

export const oauthExchangeSchema = Joi.object({
    code: Joi.string()
        .required()
        .max(2048)
        .messages({
            "string.max": "code is too long",
        }),
    nonce: nonceSchema,
});


export default {
    jwtVerifySchema,
    googleNativeLoginSchema,
    googleLoginSchema,
    oauthExchangeSchema
};